function argument(name, fallback = '') {
  const index = process.argv.indexOf(name);
  return index >= 0 ? String(process.argv[index + 1] || fallback) : fallback;
}

function compareText(left, right) { return left < right ? -1 : left > right ? 1 : 0; }
function increment(map, key, amount = 1) { map.set(String(key), (map.get(String(key)) || 0) + amount); }
function sha256(bytes) { return createHash('sha256').update(bytes).digest('hex'); }
function orderedCounts(map, limit = 100) {
  return [...map].sort((a, b) => b[1] - a[1] || compareText(a[0], b[0]))
    .slice(0, limit).map(([value, count]) => ({ value, count }));
}

function valueKind(value) {
  if (Array.isArray(value)) return 'array';
  if (value === null) return 'null';
  return typeof value;
}

function semanticTypeOf(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return '';
  const keys = ['type', 'TYPE', 'componentType', 'COMPONENT_TYPE', 'elementType', 'DTYP'];
  for (const key of keys) if (typeof value[key] === 'string' && value[key]) return value[key];
  return '';
}

function summarizeManaged(root) {
  const kinds = new Map(), keys = new Map(), types = new Map(), schemas = new Map();
  let autoGeneratedPipeCount = 0, maximumDepth = 0, objectCount = 0, arrayCount = 0;
  const stack = [{ value: root, depth: 0 }];
  while (stack.length) {
    const { value, depth } = stack.pop(); maximumDepth = Math.max(maximumDepth, depth);
    increment(kinds, valueKind(value));
    if (Array.isArray(value)) {
      arrayCount += 1;
      for (let index = value.length - 1; index >= 0; index -= 1) stack.push({ value: value[index], depth: depth + 1 });
      continue;
    }
    if (!value || typeof value !== 'object') continue;
    objectCount += 1;
    const type = semanticTypeOf(value); if (type) increment(types, type);
    if (value.AUTO_GENERATED_PIPE === true) autoGeneratedPipeCount += 1;
    if (typeof value.schema === 'string') increment(schemas, value.schema);
    for (const [key, child] of Object.entries(value)) {
      increment(keys, key); stack.push({ value: child, depth: depth + 1 });
    }
  }
  return {
    rootKind: valueKind(root), rootKeys: root && typeof root === 'object' && !Array.isArray(root)
      ? Object.keys(root).sort(compareText) : [],
    objectCount, arrayCount, maximumDepth, autoGeneratedPipeCount,
    valueKinds: orderedCounts(kinds), semanticTypes: orderedCounts(types),
    schemas: orderedCounts(schemas), mostFrequentKeys: orderedCounts(keys, 60),
  };
}

function selectZone(zones, requestedLabel) {
  const exact = zones.find((item) => item.label === requestedLabel);
  if (exact) return exact;
  const folded = requestedLabel.toUpperCase();
  const partial = zones.filter((item) => item.label.toUpperCase().includes(folded));
  assert.equal(partial.length, 1, `Expected one zone matching ${requestedLabel}, found ${partial.length}.`);
  return partial[0];
}

function boundsFor(topology, faces) {
  const indices = new Set(faces.flatMap((face) => face.vertices));
  const minimum = [Infinity, Infinity, Infinity], maximum = [-Infinity, -Infinity, -Infinity];
  for (const index of indices) for (let axis = 0; axis < 3; axis += 1) {
    minimum[axis] = Math.min(minimum[axis], topology.points[index][axis]);
    maximum[axis] = Math.max(maximum[axis], topology.points[index][axis]);
  }
  return { minimum, maximum, extent: minimum.map((value, axis) => maximum[axis] - value) };
}

function edgeDisposition(edges) {
  let boundaryEdges = 0, manifoldEdges = 0, nonManifoldEdges = 0, ambiguousEdges = 0;
  for (const edge of edges) {
    if (edge.incidentFaceIds.length === 1) boundaryEdges += 1;
    else if (edge.incidentFaceIds.length === 2) manifoldEdges += 1;
    else nonManifoldEdges += 1;
    if (edge.incidentFaceIds.length !== edge.occurrences.length || edge.a === edge.b) ambiguousEdges += 1;
  }
  return { boundaryEdges, manifoldEdges, nonManifoldEdges, ambiguousEdges };
}

function sourceName(sourceGraph, occurrence) {
  const source = sourceGraph.sourceObjects.find((item) => item.sourceObjectId === occurrence.sourceModelObjectId);
  return source?.displayName || source?.domSourceName || occurrence.sourceModelObjectId;
}

function familyName(value) {
  const name = String(value || '').trim().toUpperCase();
  if (name === 'CYLINDER') return name;
  if (name.startsWith('/')) return 'NAMED_ITEM';
  return name.match(/^[A-Z]+/)?.[0] || 'UNKNOWN';
}

function classificationSummary(sourceGraph, analysis) {
  const occurrenceById = new Map(sourceGraph.occurrences.map((item) => [item.sourceOccurrenceId, item]));
  const reasons = new Map(), methods = new Map(), familyReasons = new Map(), admittedFamilies = new Map();
  const admitted = [];
  for (const item of analysis.autoPipe.classificationDispositions || []) {
    const occurrence = occurrenceById.get(item.sourceOccurrenceId);
    const family = familyName(sourceName(sourceGraph, occurrence));
    increment(reasons, item.admitted ? 'ADMITTED' : item.reason || 'UNKNOWN');
    increment(methods, item.inferenceMethod || 'NONE');
    increment(familyReasons, `${family}:${item.admitted ? 'ADMITTED' : item.reason || 'UNKNOWN'}`);
    if (item.admitted) {
      increment(admittedFamilies, family);
      admitted.push({ sourceOccurrenceId: item.sourceOccurrenceId,
        sourceModelObjectId: item.sourceModelObjectId, geometryObjectId: item.geometryObjectId,
        sourceName: sourceName(sourceGraph, occurrence), family,
        inferenceMethod: item.inferenceMethod || 'OPEN_BOUNDARY_CYLINDER',
        spanMm: item.spanMm, radiusMm: item.A?.radiusMm || null });
    }
  }
  admitted.sort((a, b) => compareText(a.sourceOccurrenceId, b.sourceOccurrenceId));
  return { reasons: orderedCounts(reasons), methods: orderedCounts(methods),
    familyReasons: orderedCounts(familyReasons), admittedFamilies: orderedCounts(admittedFamilies), admitted };
}

async function selectionDiagnostic(selection, scope, sourceGraph) {
  const topology = decodeExactPolygonTopology(selection);
  const shells = await deriveConnectedShells(topology);
  const occurrences = scope.selectedOccurrences.filter((item) => item.geometryObjectIds.includes(topology.geometryObjectId));
  return {
    geometryObjectId: topology.geometryObjectId,
    controlPointCount: topology.points.length, faceCount: topology.faces.length,
    occurrenceCount: occurrences.length,
    occurrenceNames: occurrences.map((item) => sourceName(sourceGraph, item)).sort(compareText),
    shellCount: shells.length,
    shells: shells.map((shell) => ({
      shellId: shell.shellId, faceCount: shell.faces.length, edgeCount: shell.edges.length,
      rejectionReasons: shell.rejectionReasons, bounds: boundsFor(topology, shell.faces),
      edgeDisposition: edgeDisposition(shell.edges),
    })),
  };
}

async function geometryDiagnostics(sourceGraph, geometryBundle, zoneId) {
  const prepared = await prepareZoneGeometryEvidence({ sourceGraph, geometryBundle, zoneId });
  const records = [];
  for (const selection of prepared.selections) records.push(await selectionDiagnostic(
    selection, prepared.scope, sourceGraph));
  records.sort((a, b) => compareText(a.geometryObjectId, b.geometryObjectId));
  return { scope: {
    zoneId: prepared.scope.zoneId, zoneLabel: prepared.scope.zoneLabel,
    occurrenceCount: prepared.scope.selectedOccurrences.length,
    geometryCount: prepared.scope.selectedGeometryIds.length,
  }, records };
}

function dispositionCounts(evidence) {
  const counts = new Map();
  for (const record of evidence?.occurrenceEvidence || []) increment(counts, record.topologyDisposition || 'UNKNOWN');
  return orderedCounts(counts);
}

async function main() {
  const fbxPath = argument('--fbx'), managedPath = argument('--managed');
  const inputZipPath = argument('--input-zip'), outputZipPath = argument('--output-zip');
  const evidencePath = argument('--evidence', 'artifacts/fbx2-benchmark-audit.json');
  const zoneLabel = argument('--zone', '/GLRD-1000-CU-PI-P');
  assert.ok(fbxPath && managedPath, '--fbx and --managed are required.');
  const [fbxBytes, managedBytes, inputZipBytes, outputZipBytes] = await Promise.all([
    readFile(fbxPath), readFile(managedPath), inputZipPath ? readFile(inputZipPath) : null,
    outputZipPath ? readFile(outputZipPath) : null,
  ]);
  const managed = JSON.parse(managedBytes.toString('utf8'));
  const sourceGraph = await parseFbxInWorker(new Uint8Array(fbxBytes), { timeoutMs: 300000 });
  const geometryBundle = await parseFbxGeometryBundleInWorker(new Uint8Array(fbxBytes), { timeoutMs: 300000 });
  const zones = listFbxZoneScopeSummaries(sourceGraph);
  const targetZone = selectZone(zones, zoneLabel);
  const analysis = await analyseFbxZoneGeometry({ sourceGraph, geometryBundle,
    zoneId: targetZone.zoneId, includeZonePackageInputs: false });
  const diagnostics = await geometryDiagnostics(sourceGraph, geometryBundle, targetZone.zoneId);
  const evidence = {
    schema: 'Fbx2BenchmarkAudit.v2',
    source: { file: fbxPath, byteLength: fbxBytes.length, sha256: sha256(fbxBytes),
      archiveByteLength: inputZipBytes?.length || null, archiveSha256: inputZipBytes ? sha256(inputZipBytes) : null },
    managedStage: { file: managedPath, byteLength: managedBytes.length, sha256: sha256(managedBytes),
      archiveByteLength: outputZipBytes?.length || null, archiveSha256: outputZipBytes ? sha256(outputZipBytes) : null,
      summary: summarizeManaged(managed) },
    sourceGraph: { schema: sourceGraph.schema, sourceObjects: sourceGraph.sourceObjects.length,
      occurrences: sourceGraph.occurrences.length, geometries: sourceGraph.geometries.length,
      zoneCount: zones.length, zones },
    targetZone,
    zoneAnalysis: { status: analysis.status, counts: analysis.counts,
      autoPipeStatus: analysis.autoPipe.status, autoPipeCounts: analysis.autoPipe.counts,
      autoPipeClassifications: classificationSummary(sourceGraph, analysis),
      openBoundaryRejectionCounts: analysis.derivedPortEvidence.rejectionCounts,
      closedSolidRejectionCounts: analysis.closedSolidPipeEvidence.rejectionCounts,
      closedSolidDispositionCounts: dispositionCounts(analysis.closedSolidPipeEvidence) },
    geometryDiagnostics: diagnostics,
  };
  await writeFile(evidencePath, `${JSON.stringify(evidence, null, 2)}\n`, 'utf8');
  console.log(JSON.stringify({ targetZone, zoneAnalysis: evidence.zoneAnalysis,
    managedStage: evidence.managedStage.summary, evidencePath }, null, 2));
}

await main();
